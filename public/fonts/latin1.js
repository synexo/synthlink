/*
 * fonts/latin1.js - ISO-8859-1 (Latin-1) to Unicode, all 256 positions.
 *
 * The Amiga's character set, and so the one an Amiga board's art is drawn
 * against. Same job as cp437.js and the same shape: the OUTLINE path needs the
 * character a byte MEANS before fillText can draw it. See FONTS.md.
 *
 * GENERATED MECHANICALLY, not hand-typed - Latin-1 is the identity map, which
 * is exactly what Python's `latin_1` codec produces:
 *
 *     [ord(bytes([i]).decode('latin_1')) for i in range(256)]
 *
 * tools/tests/ttftest.js re-derives it independently and compares, as it does
 * for CP437, so a slip fails a test rather than shipping.
 *
 * ONE position is not the identity. 0xAD is U+00AD SOFT HYPHEN, which every
 * text shaper draws as nothing at all - the glyph is in the file, and fillText
 * still produces an empty cell, which would read as a font bug rather than as
 * the deliberate invisibility it is. It maps to U+2010 HYPHEN instead, and the
 * shipped face carries a cmap entry pointing that codepoint at the same glyph.
 *
 * The blank positions are policy rather than lookup, handled at the atlas
 * builder exactly as CP437's two are: 0x00-0x1F and 0x7F-0xA0 have no printable
 * character in this encoding, and must come out blank rather than as .notdef
 * boxes. 0x7F is the one that is a real loss - Topaz draws a diagonal shading
 * glyph there and Amiga artists used it - but the shipped face has no codepoint
 * for it, so it is blank until one exists.
 *
 * SynthLink's own code, GPL-3.0-or-later.
 */

