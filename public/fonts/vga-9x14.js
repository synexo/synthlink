/*
 * fonts/vga-9x14.js
 *
 * IBM VGA 9x14 ROM font — CP437 / Code Page 437, all 256 glyphs.
 *
 * THE ONLY 9-PIXEL-WIDE FONT IN THE REGISTRY, and the reason the glyph
 * encoding grew a stride: 9 pixels do not fit in a byte, so each pixel row is
 * TWO bytes (big-endian, MSB = leftmost pixel), the low 7 bits of the second
 * byte unused. Every 8-wide font here stays at one byte per row. See
 * `bytesPerRow` in index.js.
 *
 * This font exists to carry 40-column mode, and selecting it IS how 40-column
 * mode is entered — see the `cols: 40` on its registry entry. The arithmetic
 * that makes the pairing worth it, at a fixed terminal width W:
 *
 *   8x16 at 80x25 -> 640x400 canvas -> height 0.625 W   (the baseline)
 *   8x16 at 40x25 -> 320x400 canvas -> height 1.250 W   (2.00x — unusable)
 *   9x14 at 40x25 -> 360x350 canvas -> height 0.972 W   (1.56x)
 *
 * A 9-wide, 14-tall cell is both wider and shorter than 8x16, and those two
 * pull in the same direction here: halving the column count doubles the cell's
 * on-screen scale, and the shorter, wider cell claws most of that back out of
 * the height. Any 8-wide font at 40 columns would simply double the terminal's
 * height, which is what ruled out reusing one.
 *
 * ── Attribution / licence ────────────────────────────────────────────────
 * Source:  "Bm437 IBM VGA 9x14", from VileR's Ultimate Oldschool PC Font Pack
 *          (int10h.org), distributed as a Windows .FON bitmap font.
 * Author:  VileR — FON conversion, 2020 (v2.2, Nov 2020).
 * Licence: Creative Commons Attribution-ShareAlike 4.0 International
 *          (CC BY-SA 4.0) — https://creativecommons.org/licenses/by-sa/4.0/
 *
 * This file is a mechanical conversion of that .FON: the FNT resource's glyph
 * bitmaps, extracted verbatim into a byte array. No glyph shapes were altered.
 * As an adaptation of a CC BY-SA 4.0 work, THIS FILE stays under CC BY-SA 4.0
 * and must keep this notice — it is licensed separately from the rest of
 * SynthLink (LGPL-3.0), which the share-alike term does not affect, this being
 * a data asset rather than linked code. See PROVENANCE.md.
 *
 * Metrics read from the FNT header of the source file (NOT assumed from its
 * name — the resource was located through the NE resource table, dfPixWidth /
 * dfPixHeight read at 0x56/0x58, glyph offsets from the char table at 0x76):
 *   dfVersion 0x0200                 fixed pitch
 *   dfPixWidth 9    dfPixHeight 14   dfFirstChar 0   dfLastChar 255
 *   dfAscent 11                      28 bytes per glyph
 *
 * FNT v2.0 stores a glyph COLUMN-major — all 14 rows of byte-column 0, then
 * all 14 rows of byte-column 1. This file is row-major, so the conversion
 * re-interleaves the two columns; the bits themselves are untouched.
 *
 * Measured ink metrics vs the IBM VGA 8x16 baseline (cap 10, x-height 7):
 *   cap height 9 rows, x-height 6 rows — SMALLER in raw pixels. That is not a
 *   contradiction: at 40 columns the cell renders 1.78x larger than an 80-column
 *   8x16 cell does, so on screen the cap height goes from 10 units to ~16. The
 *   font is chosen for what it measures AFTER the column halving, which is the
 *   only mode it is ever used in.
 *
 * Two things measurement settled here (the checks DEVLOG.md asks for):
 *   - Cell height 14 is EVEN, so the two-phase 0xB0/0xB1 checkerboards keep
 *     their phase across the cell boundary. The banding that ruled out the
 *     8x19 PRC19 font is intrinsic to ODD heights and does not arise here.
 *   - 0xB2 is the classic checkerboard, not PRC19's diagonal, so ANSI art
 *     shades as it should.
 *
 * KNOWN, DELIBERATE: this is a true 9-DOT font and follows the VGA hardware
 * rule — only 0xC0-0xDF have their 8th column duplicated into the 9th. That is
 * what makes the box-drawing characters join across cells (verified on 0xC4,
 * 0xB3, 0xDA, 0xDB). The shade blocks 0xB0/0xB1/0xB2 are NOT in that range, so
 * they carry a blank 9th column and a large shaded fill shows a faint vertical
 * gap every 9 pixels — exactly as it did on a real EGA/VGA in 9-dot text mode,
 * and more visible at 40 columns because everything is. Kept verbatim by
 * choice; patching those three glyphs would fix the tiling at the cost of no
 * longer being the font VileR converted.
 */

